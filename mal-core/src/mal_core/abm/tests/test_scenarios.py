@pytest.mark.parametrize("scenario_id", ["E01", "E02", "E13"])
def test_determinism_same_seed_byte_identical(scenario_id):
    (a,) = h.run_scenario(scenario_id, out_root=h.CHECK_DIR / "_det_a")
    (b,) = h.run_scenario(scenario_id, out_root=h.CHECK_DIR / "_det_b")
    da, db = h.artifact_digests(a.out_dir), h.artifact_digests(b.out_dir)
    assert da and da == db


