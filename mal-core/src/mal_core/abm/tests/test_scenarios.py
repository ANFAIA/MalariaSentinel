"""pytest entry point of the scenario harness (plan 13.3.1, Nivel 4/5).

What this file asserts, and what it deliberately does not
---------------------------------------------------------
The scenario catalogue (``scenarios/catalog.yaml``, rendered into the ABM
conceptual document by ``tools/gen_concepts_values.py``) says, for each of
E00..E18, what the scenario is for and what should happen. The behaviours
the plan wants (the cascade, the ledger, the blood meal...) do not exist yet;
each is written by the step that implements it. Until then the harness
asserts four kinds of fact, and every test says which one it is:

* **Seeding fidelity** (all 19 scenarios, real checks): the scenario file is
  read by the engine, and what the engine holds afterwards matches it. Adults
  obey the conservation identity ``adults(d) = adults(d-1) - deaths(d) +
  emerged(d)`` on every day; seeded pupae emerge; the COG snapshot and the
  cohort log agree on the number of adults.
* **Baseline pins** (E00/E01/E02): facts about the *current* chain, measured
  in Paso 1. They are known failures, not expectations. If the chain changes,
  the pin fails on purpose and whoever changed it updates the pin and the
  catalogue entry in the same commit.
* **Target gates as strict expected failures** (``xfail(strict=True)``): the
  plan's pre-registered target (E01: no bite at 200 m; E02: no bite at
  2000 m; GIF: one frame per phase). They fail today. When the step that owns
  them makes them pass, strict mode turns the test red and forces the
  promotion to a plain assertion: the target cannot start passing unnoticed.
* **Determinism** (Nivel 5): same seed => byte-identical artefacts, other
  seed => different artefacts.

A scenario run that exits 0 proves nothing about behaviour; none of these
tests relies on that alone.

Needs the rebuilt binary (``abm/bin/mal_abm_fast_darwin``); the synthetic AOI
is regenerated by the session fixture.
"""

from __future__ import annotations

import subprocess
import sys

import pytest
import yaml

from scenarios import harness as h

pytestmark = pytest.mark.skipif(
    sys.platform != "darwin", reason="binary is mal_abm_fast_darwin"
)

CELL_M = 1000.0
GRID = 10


@pytest.fixture(scope="session", autouse=True)
def synthetic_aoi():
    script = h.REPO_ROOT / "mal-execution" / "scripts" / "make_synthetic_aoi.py"
    subprocess.run(
        [sys.executable, str(script), "--out", str(h.DATA_ROOT / h.AOI_SLUG),
         "--scenario", "E00"],
        check=True, cwd=h.REPO_ROOT, capture_output=True,
    )


_RUNS: dict[str, list[h.ScenarioRun]] = {}


def runs_of(scenario_id: str) -> list[h.ScenarioRun]:
    """Run each scenario once per session and report it (cached)."""
    if scenario_id not in _RUNS:
        runs = h.run_scenario(scenario_id)
        h.write_reports(runs)
        _RUNS[scenario_id] = runs
    return _RUNS[scenario_id]


def cell_of(x_m: float, y_m: float) -> tuple[int, int]:
    """(row, col) of a metric AOI position; row 0 is the northern row."""
    return GRID - 1 - int(y_m // CELL_M), int(x_m // CELL_M)


def cohort_days(run: h.ScenarioRun) -> list[dict]:
    stem = f"{h.AOI_SLUG}_abm_seed{int(run.spec['seed']):04d}_cohort.json"
    return yaml.safe_load((run.out_dir / stem).read_text())["daily"]


