@pytest.mark.parametrize("scenario_id", h.ALL_IDS)
def test_adult_conservation_identity(scenario_id):
    """FIDELITY. adults(d) = adults(d-1) - deaths(d) + emerged(d), from the
    seeded count. Catches agents dropped or duplicated at seeding and any
    day on which the engine loses or invents a mosquito."""
    for run in runs_of(scenario_id):
        previous = len(run.spec["agents"])
        for d in cohort_days(run):
            assert d["n_adults"] == previous - d["n_deaths"] + d["n_emerged"], (
                f"{scenario_id}/{run.variant} day {d['day']}: "
                f"{previous} - {d['n_deaths']} + {d['n_emerged']} != {d['n_adults']}")
            previous = d["n_adults"]


@pytest.mark.parametrize("scenario_id", h.ALL_IDS)
def test_cog_matches_cohort_log(scenario_id):
    """FIDELITY. Two independent outputs (the COG adult-cell band and the
    cohort log) report the same number of adults on every snapshot day."""
    for run in runs_of(scenario_id):
        adults = [d["n_adults"] for d in cohort_days(run)]
        for i, snap in enumerate(run.observed["adult_cells_by_snapshot"]):
            in_cog = sum(v for _, _, v in snap["occupied_cells"])
            assert in_cog == adults[i], (
                f"{scenario_id} {snap['snapshot']}: COG {in_cog} vs log {adults[i]}")


def test_e07_seeded_pupae_emerge():
    """FIDELITY. The breeding site outside the candidate union is live: the
    seeded pupae reach adulthood (some, not necessarily all, survive)."""
    (run,) = runs_of("E07")
    seeded = sum(a["count"] for a in run.spec["aquatic"])
    emerged = sum(d["n_emerged"] for d in cohort_days(run))
    assert 0 < emerged <= seeded


@pytest.mark.parametrize("scenario_id", ["E13", "E15"])
def test_seed_sensitivity_of_mortality(scenario_id):
    """FIDELITY. Two master seeds give different mortality in a 100+ agent
    run: the sub-streams really derive from the one --seed (plan 13.4)."""
    (a,) = runs_of(scenario_id)
    (b,) = h.run_scenario(scenario_id, out_root=h.CHECK_DIR / "_seed_b",
                          seed_override=a.spec["seed"] + 1)
    deaths = lambda r: [d["n_deaths"] for d in cohort_days(r)]  # noqa: E731
    assert deaths(a) != deaths(b)


