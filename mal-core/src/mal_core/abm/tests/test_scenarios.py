CATALOG_FIELDS = {"title", "purpose", "setup", "implies", "expected", "closes",
                  "executable_today", "today", "verified_now", "gif"}


def test_catalog_documents_every_scenario():
    """Every scenario has a complete catalogue entry; the generator renders it
    into the ABM conceptual document."""
    catalog = yaml.safe_load((h.SCENARIOS_DIR / "catalog.yaml").read_text())
    assert sorted(catalog) == h.ALL_IDS
    for sid, entry in catalog.items():
        assert CATALOG_FIELDS <= set(entry), f"{sid}: missing {CATALOG_FIELDS - set(entry)}"
        assert all(str(entry[k]).strip() for k in CATALOG_FIELDS), f"{sid}: empty field"


