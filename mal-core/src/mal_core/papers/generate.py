"""Render ``papers/REFERENCES.md`` from the manifest.

Output is deterministic: no timestamps, themes in alphabetical order, entries
inside a theme ordered by (year, first author, id). Every table has a header row
and a separator row, and no blank line splits a table. The header on every table
is the regression guard for the broken table that the old index had at line 57.
"""

from __future__ import annotations

from pathlib import Path

from .manifest import Manifest

HEADERS = ("#", "Citation", "Class", "Licence (as recorded)", "DOI", "Status")
_PREAMBLE = """# Paper references

<!-- Generated by `malariasim papers generate` from papers/manifest.json. Do not edit by hand. -->

This index lists every entry of the paper manifest, one section per theme. The
papers themselves are not versioned (D4). Obtain them with `malariasim papers fetch`,
and cite them by DOI, never by a file path (D21).
"""


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _citation(authors: str | None, title: str, journal: str | None, year: int | None) -> str:
    """Citation line; a null author, journal or year is written as a visible gap, never invented."""
    head = f"{authors.rstrip('.')}. " if authors else "[no authors recorded]. "
    body = f"{head}{title.rstrip('.')}."
    if journal:
        body += f" *{journal}*"
    return body + (f" ({year})." if year is not None else " (n.d.).")


def _table(rows: list[list[str]]) -> list[str]:
    lines = [
        "| " + " | ".join(HEADERS) + " |",
        "|" + "|".join("---" for _ in HEADERS) + "|",
    ]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def render_references(manifest: Manifest) -> str:
    """The full text of ``REFERENCES.md``. Pure and deterministic."""
    out: list[str] = [_PREAMBLE.rstrip("\n"), ""]
    number = 0
    for theme in sorted({e.theme for e in manifest.entries}):
        entries = sorted(
            (e for e in manifest.entries if e.theme == theme),
            key=lambda e: (e.year or 0, (e.authors or "").split(",")[0].strip().lower(), e.id),
        )
        rows: list[list[str]] = []
        for entry in entries:
            number += 1
            if entry.doi:
                doi_cell = f"[{entry.doi}](https://doi.org/{entry.doi})"
            else:
                doi_cell = "none"
            rows.append(
                [
                    str(number),
                    _cell(_citation(entry.authors, entry.title, entry.journal, entry.year)),
                    entry.paper_class,
                    _cell(entry.licence_as_recorded),
                    _cell(doi_cell),
                    _cell(entry.expected_status),
                ]
            )
        out += [f"## {theme}", ""] + _table(rows) + [""]
    return "\n".join(out).rstrip("\n") + "\n"


def write_references(manifest: Manifest, path: Path) -> bool:
    """Write the index. Returns True when the file content changed."""
    text = render_references(manifest)
    previous = path.read_text(encoding="utf-8") if path.is_file() else None
    if previous == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def is_up_to_date(manifest: Manifest, path: Path) -> bool:
    """Drift gate: True when ``path`` holds exactly what ``render_references`` produces."""
    return path.is_file() and path.read_text(encoding="utf-8") == render_references(manifest)
