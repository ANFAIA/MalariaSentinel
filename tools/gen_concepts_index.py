#!/usr/bin/env python3
"""Generate the site's index of conceptual documents.

The documentation page (``docs/documentacion.html``) lists one document per
pipeline stage. That list used to be written by hand inside the HTML, which
means a stage added to the tree does not appear until somebody remembers to
edit the page. This script writes the list from the tree instead, so the
page can only be wrong in the two ways a generated list can be wrong: the
tree changed and the script was not re-run, or the script was re-run and the
page was not reloaded.

The output is a JavaScript fragment the page includes:

    <script src="concepts/generated/stages.js"></script>

It is plain JavaScript rather than JSON because the page loads it with a
``<script>`` tag: a JSON file would need a fetch, and the page is also
opened from the filesystem during review, where a fetch of a local file is
blocked by the browser's origin rules.

Usage:
    uv run python tools/gen_concepts_index.py [--check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CONCEPTS = REPO / "docs" / "concepts"
OUT = CONCEPTS / "generated" / "stages.js"

# The order the page lists the stages in: the order the pipeline runs.
STAGES = ("download", "ingest", "abm", "scoring", "training", "prediction")

# The ABM stage's source is the ODD document; its PDF is published under
# the stage's name.
SOURCE_NAME = {
    "abm": "odd-2010-malariasentinel.tex",
}


def source_for(stage: str) -> Path:
    return CONCEPTS / stage / SOURCE_NAME.get(stage, f"{stage}.tex")


def entries() -> list[dict[str, str]]:
    out: list[dict[str, str]] = []
    for stage in STAGES:
        source = source_for(stage)
        if not source.exists():
            raise SystemExit(
                f"gen_concepts_index: no document for stage '{stage}' "
                f"(expected {source.relative_to(REPO)})"
            )
        out.append(
            {
                "slug": stage,
                "stage": stage,
                "pdf": f"concepts/{stage}/{stage}.pdf",
                "source": f"concepts/{stage}/{source.name}",
            }
        )
    return out


def render(entries: list[dict[str, str]]) -> str:
    lines = [
        "// Generated by tools/gen_concepts_index.py -- do not edit.",
        "// The list of conceptual documents, written from the tree.",
        "",
        "const STAGES = [",
    ]
    for entry in entries:
        lines.append(
            "  {{ slug: '{slug}', stage: '{stage}', pdf: '{pdf}', source: '{source}' }},".format(
                **entry
            )
        )
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated file differs from the tree",
    )
    args = parser.parse_args()

    text = render(entries())
    if args.check:
        if not OUT.exists():
            print(f"gen_concepts_index: {OUT} does not exist", file=sys.stderr)
            return 1
        current = OUT.read_text(encoding="utf-8")
        if current != text:
            print(
                f"gen_concepts_index: {OUT.relative_to(REPO)} is stale — "
                "run `uv run python tools/gen_concepts_index.py`",
                file=sys.stderr,
            )
            return 1
        print(f"gen_concepts_index: {OUT.relative_to(REPO)} is current")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"gen_concepts_index: wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
