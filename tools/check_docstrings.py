#!/usr/bin/env python3
"""Report the public surface of the Python packages that has no docstring.

The technical reference (``docs/reference/python/``) is generated by pdoc
from these docstrings. pdoc shows an entity without a docstring as a bare
signature — a reader sees the name and the type and nothing else — so an
undocumented entity is a hole in the published reference.

This tool measures that hole. It reports the entities that have no
docstring, per module, and it can fail (exit 1) when any remain, so the
reference's completeness is a property the build checks rather than a
property somebody remembers.

Usage:
    uv run python tools/check_docstrings.py            # report, always exit 0
    uv run python tools/check_docstrings.py --check    # exit 1 if any gap remains
    uv run python tools/check_docstrings.py --public-only   # only the public surface

What counts as a gap:
  * a class with no docstring;
  * a function or method with no docstring.

The default is the *whole* surface, private helpers included: a helper
whose name does not say what it does is a trap for the next reader. With
``--public-only`` only the entities pdoc renders by default are counted
(everything whose name does not start with an underscore), which is the
floor the published reference must clear.

The packages and their roots are declared in ``PACKAGES`` below, so the
tool reads the same tree the reference is generated from.
"""

from __future__ import annotations

import argparse
import ast
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[1]

#: package name -> directory that holds it, relative to the repository root
PACKAGES: dict[str, str] = {
    "mal_core": "mal-core/src/mal_core",
    "mal_commonlib": "mal-commonlib/src/mal_commonlib",
}

#: directories that are not part of the published surface. pdoc does not
#: publish them either: a module under ``tests/`` or ``scripts/`` never
#: reaches the reference, so a gap there is not a hole in it.
SKIP_DIRS = {"__pycache__", "tests", "test", "scripts"}


def _is_public(name: str) -> bool:
    return not name.startswith("_")


def _published(rel: pathlib.Path) -> bool:
    """True when the module is part of the surface the reference renders.

    A module under ``tests/`` or ``scripts/`` is not published, and a
    module whose name starts with an underscore is private by convention
    (``_legacy``: the retired loaders, kept for the record and reachable
    by nothing).
    """
    if set(rel.parts[:-1]) & SKIP_DIRS:
        return False
    return not any(part.startswith("_") for part in rel.parts[:-1])


def _walk_package(root: pathlib.Path, public_only: bool) -> list[tuple[str, str]]:
    """Every class and function in ``root`` that has no docstring.

    Returns ``(module, entity)`` pairs, where ``entity`` names the
    class or the function the way a reader would recognise it.
    """
    gaps: list[tuple[str, str]] = []
    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root)
        if not _published(rel):
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError as exc:  # pragma: no cover - a broken file is a build failure
            print(f"check_docstrings: {rel} does not parse: {exc}", file=sys.stderr)
            continue
        module = str(rel).removesuffix(".py").removesuffix("/__init__")
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                if public_only and not _is_public(node.name):
                    continue
                if not ast.get_docstring(node):
                    gaps.append((module, f"class {node.name}"))
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if public_only and not _is_public(node.name):
                    continue
                if not ast.get_docstring(node):
                    gaps.append((module, f"{node.name}()"))
    return gaps


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if any gap remains")
    parser.add_argument(
        "--public-only",
        action="store_true",
        help="count only the entities pdoc renders by default",
    )
    args = parser.parse_args()

    total = 0
    for package, root in PACKAGES.items():
        gaps = _walk_package(REPO / root, args.public_only)
        if not gaps:
            continue
        print(f"{package}: {len(gaps)} entities without a docstring")
        for module, entity in gaps:
            print(f"  {module}.{entity}")
        total += len(gaps)

    if total == 0:
        print("check_docstrings: every documented entity has a docstring")
        return 0
    print(f"check_docstrings: {total} entities have no docstring")
    return 1 if args.check else 0


if __name__ == "__main__":
    raise SystemExit(main())
